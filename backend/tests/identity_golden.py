"""The golden table for app.identity: what is the same recording, the same
album, the same artist or path, and which copy of a file is better.

Data only (not named test_*, so discovery doesn't load it): test_p1_identity
checks app.identity against every row, and then every caller that used to
keep its own rule.

Each row is (kind, a, b, policy, expected, case).

  recording  a: the wanted side (a release or YouTube Music track), b: the
             file held. policy None asks identity.same_recording; "assign"
             asks the one assignment matcher (identity.assign), where a
             release track's number and context count too.
  album      policy "edition" (one release group is one album only in the
             same edition), "release_group" (any edition), or "split"
             (units.split_key: may one folder's files carry both names and
             still be one album?). A side is a name, {"name", "hints",
             "group", "kind"}, or a file row ({"path", "album", ...}).
  path, artist
             two spellings: one folder or one artist?
  quality    two copies of one track: is a the better file? Both ranks
             (with tags and without) must agree.

Cases come from the 2026-11 review (docs/review/2026-11-triage.md, §4 and
§5 P1-F1) and the phase-0 carry-overs. When in doubt a row says "not the
same": a missed duplicate is harmless; a false one deletes a file.
"""


def rec(title, length=None, **kw) -> dict:
    """A track: the YouTube Music or release side, or a file with `path`."""
    return {"title": title, "duration_sec": length, **kw}


def pos(title, length, number, **kw) -> dict:
    """A track with its place on the release (or the YouTube Music album)."""
    return {"title": title, "duration_sec": length, "track_number": number, **kw}


